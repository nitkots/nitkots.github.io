/**
 * Bundles the homepage sphere into one classic script, assets/explore/home.bundle.js,
 * so index.html works when opened straight from disk (file://), where browsers
 * refuse to load local ES modules. Three.js is still fetched from the CDN.
 *
 *   node tools/build-home.mjs          write the bundle
 *   node tools/build-home.mjs --check  exit 1 if the bundle is out of date
 *
 * The source modules in assets/explore/ stay the thing you edit; rerun this after.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/explore');
const OUT = join(dir, 'home.bundle.js');
const THREE_URL = 'https://cdn.jsdelivr.net/npm/three@0.169.0/build/three.module.min.js';

const read = (f) => readFileSync(join(dir, f), 'utf8');
// Drop single-line static imports and `export` keywords: everything shares one scope.
const strip = (src) => src
  .replace(/^import\s[^;]*;\s*$/gm, '')
  .replace(/^export\s+(const|function|class|let)\s/gm, '$1 ');

export function buildHome() {
  const sphere = strip(read('sphere.js'));
  let home = strip(read('home.js'));
  const dynamicImport = "import('./sphere.js')";
  if (!home.includes(dynamicImport)) throw new Error(`home.js no longer contains ${dynamicImport}`);
  home = home.replace(dynamicImport,
    `import(${JSON.stringify(THREE_URL)}).then((THREE) => ({ SphereScene: makeSphereScene(THREE) }))`);

  return `/* GENERATED by tools/build-home.mjs from assets/explore/*.js. Do not edit; edit the sources and rebuild. */
(function () {
'use strict';
${strip(read('config.js'))}
${strip(read('home-config.js'))}
${strip(read('graph.js'))}
${strip(read('navigation.js'))}
// sphere.js, with Three.js passed in once it has loaded from the CDN.
function makeSphereScene(THREE) {
${sphere}
return SphereScene;
}
${home}
})();
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = buildHome();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== code) { console.error('home.bundle.js is out of date: run node tools/build-home.mjs'); process.exit(1); }
    console.log('home.bundle.js is up to date');
  } else {
    writeFileSync(OUT, code);
    console.log(`wrote ${OUT} (${(code.length / 1024).toFixed(1)} KB)`);
  }
}
